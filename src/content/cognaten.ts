/**
 * De Woordenstamboom: families van woorden die over de talen heen dezelfde
 * stam delen. Wie in het Spaans "amigo" leert, herkent daarna moeiteloos
 * ami, amico en amigo. Dat is het idee: één woord leren opent er vijf.
 */
export interface FamilieLid {
  /** het woord in die taal, precies zoals het in de cursus staat */
  woord: string
  /** de Nederlandse betekenis */
  nl: string
}

export interface WoordFamilie {
  /** unieke sleutel, kleine letters, bv. 'amicus' */
  id: string
  /** de stam waar alles vandaan komt, bv. 'amicus' */
  stam: string
  /** waar de stam vandaan komt */
  herkomst: 'Latijn' | 'Germaans' | 'Grieks' | 'Arabisch' | 'Frankisch'
  /** wat de stam letterlijk betekende, in het Nederlands */
  stamBetekenis: string
  /** één zin die dit leuk of memorabel maakt, in het Nederlands, zonder middenstreepjes */
  weetje: string
  /** per taal het familielid; een taal mag ontbreken */
  leden: Partial<Record<CourseId, FamilieLid>>
}

