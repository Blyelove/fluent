/** Maakt van een woord een zoeksleutel: kleine letters, accenten weg, ligaturen uitgeschreven */
function normaliseer(woord: string): string {
  return woord
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/œ/g, 'oe')
    .replace(/æ/g, 'ae')
    .replace(/ß/g, 'ss')
    .replace(/[‘’ʼ´`]/g, "'")
    .trim()
}

/** Lidwoorden die we bij een mislukte zoekopdracht nog even wegknippen */
const LIDWOORDEN = [
  'el', 'la', 'los', 'las', 'un', 'una',
  'le', 'les', 'une', 'du', 'de',
  'il', 'lo', 'gli', 'uno',
  'o', 'a', 'os', 'as', 'um', 'uma',
  'der', 'die', 'das', 'ein', 'eine',
  'the',
]

function sleutel(taal: CourseId, woord: string): string {
  return taal + ':' + normaliseer(woord)
}

/** Eén keer opgebouwd bij het laden van de module, daarna is opzoeken gratis */
const INDEX: Map<string, WoordFamilie> = (() => {
  const kaart = new Map<string, WoordFamilie>()
  for (const familie of FAMILIES) {
    for (const taal of Object.keys(familie.leden) as CourseId[]) {
      const lid = familie.leden[taal]
      if (!lid) continue
      const s = sleutel(taal, lid.woord)
      if (!kaart.has(s)) kaart.set(s, familie)
    }
  }
  return kaart
})()

/** Zoek de familie waar dit woord in deze taal bij hoort */
export function familieVan(taal: CourseId, woord: string): WoordFamilie | undefined {
  const direct = INDEX.get(sleutel(taal, woord))
  if (direct) return direct

  const kaal = normaliseer(woord)

  // Tweede kans: lidwoord met spatie ervoor weghalen, bv. "el gato" of "der Kaffee"
  const delen = kaal.split(/\s+/)
  if (delen.length > 1 && LIDWOORDEN.includes(delen[0])) {
    const zonder = INDEX.get(taal + ':' + delen.slice(1).join(' '))
    if (zonder) return zonder
  }

  // Derde kans: samengetrokken lidwoord, bv. "l'eau", "l'amico", "un'ora"
  const samengetrokken = kaal.match(/^[a-z]{1,4}'\s*(.+)$/)
  if (samengetrokken) return INDEX.get(taal + ':' + samengetrokken[1])

  return undefined
}

